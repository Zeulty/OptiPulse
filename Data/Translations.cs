        public static string Get(AppLanguage lang, string key)
        {
            var map = lang switch
            {
                AppLanguage.Turkish => ChromeTr,
                AppLanguage.Spanish => ChromeEs,
                AppLanguage.Chinese => ChromeZh,
                _ => ChromeEn
            };
            if (map.TryGetValue(key, out string? value)) return value;
            return ChromeEn.GetValueOrDefault(key, key);
        }

        public static TweakTexts? GetTweak(AppLanguage lang, string id) => lang switch
        {
            AppLanguage.Turkish => TweakTr.GetValueOrDefault(id),
            AppLanguage.Spanish => TweakEs.GetValueOrDefault(id),
            AppLanguage.Chinese => TweakZh.GetValueOrDefault(id),
            _ => null
        };

